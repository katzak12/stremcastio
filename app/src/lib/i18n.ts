/** The active strings. Mutated in place by setAppLanguage so existing imports stay valid. */
export const t: Strings = { ...en }

let current = 'en'

export function setAppLanguage(code: string | undefined): void {
  const next = code && STRINGS[code] ? code : 'en'
  if (next === current) return
  current = next
  Object.assign(t, STRINGS[next])
}

export function stringsFor(code: string): Strings {
  return STRINGS[code] ?? en
}
